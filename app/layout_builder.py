import os
import re


def build_comic_layout(
    image_paths: list,
    full_story: str,
    outline: list
) -> list:
    """
    Build the comic layout used by:
    - comic_preview.html
    - PDF exporter

    image_paths:
        Filesystem paths returned by image generation.

    full_story:
        Story generated by Gemini.

    outline:
        Panel information generated by Gemini.
    """

    # ---------------------------------------------------------
    # 1. Split the story into panel sections
    # ---------------------------------------------------------

    if "**Panel" in full_story:
        story_panels = full_story.split("**Panel")
        story_panels = [
            f"**Panel{panel}"
            for panel in story_panels
            if panel.strip()
        ]

    elif "Panel " in full_story:
        story_panels = re.split(
            r"(?=Panel\s+\d+:)",
            full_story
        )
        story_panels = [
            panel
            for panel in story_panels
            if panel.strip()
        ]

    else:
        paragraphs = [
            p.strip()
            for p in full_story.split("\n\n")
            if p.strip()
        ]

        if len(paragraphs) >= len(outline):
            story_panels = paragraphs
        else:
            story_panels = [full_story] * len(outline)

    # Make sure we have enough story sections
    while len(story_panels) < len(outline):
        idx = len(story_panels) + 1

        story_panels.append(
            f"**Panel {idx}**\n"
            "**NARRATION:** The story continues."
        )

    # ---------------------------------------------------------
    # 2. Build panel layout
    # ---------------------------------------------------------

    layout = []

    for idx, (image, text, panel_info) in enumerate(
        zip(image_paths, story_panels, outline),
        start=1
    ):

        # -----------------------------------------------------
        # Clean story text
        # -----------------------------------------------------

        lines = [
            line.strip()
            for line in text.strip().splitlines()
            if line.strip()
        ]

        if lines:
            first_line = lines[0].lower()

            if (
                "panel" in first_line
                or first_line.startswith("**")
            ):
                cleaned_text = "\n".join(lines[1:]).strip()
            else:
                cleaned_text = "\n".join(lines).strip()
        else:
            cleaned_text = ""

        # -----------------------------------------------------
        # Extract caption / narration / dialogue
        # -----------------------------------------------------

        caption = ""
        narration = ""
        dialogue = ""

        caption_match = re.search(
            r"\*{0,2}CAPTION:\*{0,2}\s*(.*?)(?=\n\s*\*{0,2}[A-Z]+:\*{0,2}|$)",
            cleaned_text,
            re.DOTALL | re.IGNORECASE
        )

        narration_match = re.search(
            r"\*{0,2}NARRATION:\*{0,2}\s*(.*?)(?=\n\s*\*{0,2}[A-Z]+:\*{0,2}|$)",
            cleaned_text,
            re.DOTALL | re.IGNORECASE
        )

        dialogue_match = re.search(
            r"\*{0,2}DIALOGUE:\*{0,2}\s*(.*?)(?=\n\s*\*{0,2}[A-Z]+:\*{0,2}|$)",
            cleaned_text,
            re.DOTALL | re.IGNORECASE
        )

        if caption_match:
            caption = caption_match.group(1).strip()

        if narration_match:
            narration = narration_match.group(1).strip()

        if dialogue_match:
            dialogue = dialogue_match.group(1).strip()

        # -----------------------------------------------------
        # 3. IMAGE PATH HANDLING
        # -----------------------------------------------------

        # Convert Windows backslashes to forward slashes
        raw_image_path = str(image).replace("\\", "/")

        # Remove leading ./ or /
        clean_image_path = raw_image_path.lstrip("./")

        # -----------------------------------------------------
        # Find the actual filename
        #
        # Example:
        # C:/.../static/panels/fac0bfc141_panel_1.png
        #
        # becomes:
        # fac0bfc141_panel_1.png
        # -----------------------------------------------------

        image_filename = os.path.basename(clean_image_path)

        # -----------------------------------------------------
        # Filesystem path
        #
        # Used by PDF exporter.
        # -----------------------------------------------------

        if "static/panels/" in clean_image_path:
            relative_image_path = (
                "static/panels/" + image_filename
            )
        else:
            relative_image_path = clean_image_path

        # -----------------------------------------------------
        # Web path
        #
        # This MUST be:
        #
        # /static/panels/filename.png
        # -----------------------------------------------------

        web_image_path = (
            "/static/panels/" + image_filename
        )

        # -----------------------------------------------------
        # Panel information
        # -----------------------------------------------------

        panel_title = panel_info.get(
            "title",
            f"Panel {idx}"
        )

        scene_description = panel_info.get(
            "scene_description",
            ""
        )

        image_prompt = panel_info.get(
            "image_prompt",
            ""
        )

        # -----------------------------------------------------
        # Add panel
        # -----------------------------------------------------

        layout.append({
            "panel": idx,
            "panel_number": idx,

            "title": panel_title,

            # Filesystem path
            "image_path": relative_image_path,

            # Browser URL
            "web_image_path": web_image_path,

            "text": cleaned_text,

            "scene_description": scene_description,

            "image_prompt": image_prompt,

            "caption": caption,

            "narration": narration,

            "dialogue": dialogue
        })

    return layout